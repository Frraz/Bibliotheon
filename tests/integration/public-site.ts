import { testOrigin } from '../fixtures/origin'
import assert from 'node:assert/strict'
import { seedSite } from '../fixtures/site'

const base = testOrigin
const seed = await seedSite()
const get = (path: string) => fetch(base + path, { redirect: 'manual' })
try {
  const [book] = seed.books
  for (const path of ['/', '/ebooks', `/ebooks/${book.slug}`, `/artigos/${seed.article.slug}`, `/temas/${seed.theme.slug}`, '/sobre', '/contato', '/privacidade', '/termos']) assert.equal((await get(path)).status, 200, path)
  const search = await (await get('/ebooks?q=edicao')).text()
  assert.ok(search.includes(book.title), 'Busca sem acento encontra título acentuado.')
  const empty = await (await get('/ebooks?q=zzzzzzzsemresultado')).text()
  assert.ok(empty.includes('Nenhum livro para esta busca.'))
  assert.equal((await get('/ebooks?page=0')).status, 404)
  assert.equal((await get('/ebooks?page=99999')).status, 404)
  assert.equal((await get(`/ebooks/${seed.draft.slug}`)).status, 404)
  assert.equal((await get('/api/ebooks')).status, 403)
  assert.equal((await get(`/api/v1/media/${seed.cover.id}`)).status, 200)
  const previewAnon = await get(`/preview/ebooks/${seed.draft.id}`)
  assert.equal(previewAnon.status, 307)
  assert.ok(previewAnon.headers.get('location')?.includes('/admin/login'))
  const login = await fetch(base + '/api/admin-users/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: seed.owner.email, password: seed.password }) })
  const { token } = await login.json() as { token: string }
  const preview = await fetch(base + `/preview/ebooks/${seed.draft.id}`, { headers: { Authorization: `JWT ${token}` } })
  assert.equal(preview.status, 200)
  assert.ok(preview.headers.get('x-robots-tag')?.includes('noindex'))
  const checkout = await get(`/comprar/${seed.offers[0].id}?utm_source=local`)
  assert.equal(checkout.status, 302)
  assert.equal(checkout.headers.get('location'), seed.offers[0].checkoutUrl)
  const affiliate = await get(`/comprar/${seed.offers[1].id}?c=${seed.campaign.code}`)
  assert.equal(affiliate.status, 302)
  assert.equal(affiliate.headers.get('location'), seed.campaign.affiliateUrl)
  assert.equal((await get(`/comprar/${seed.offers[0].id}?c=${seed.campaign.code}`)).status, 400)
  assert.equal((await get(`/comprar/${seed.offers[0].id}?url=https://evil.invalid`)).status, 400)
  const affiliatePage = await (await get(`/ebooks/${book.slug}?c=${seed.campaign.code}`)).text()
  assert.ok(affiliatePage.includes(`comprar/${seed.offers[1].id}`))
  assert.ok(!affiliatePage.includes(`comprar/${seed.offers[0].id}`), 'LP afiliada não oferece destino do produtor.')
  await seed.payload.update({ collection: 'offers', id: seed.offers[1].id, data: { active: false }, ...seed.auth })
  assert.equal((await get(`/comprar/${seed.offers[1].id}?c=${seed.campaign.code}`)).status, 410)
  const inactive = await (await get(`/ebooks/${book.slug}?c=${seed.campaign.code}`)).text()
  assert.ok(inactive.includes('oferta desta campanha está indisponível'))
  assert.ok(!inactive.includes(`comprar/${seed.offers[0].id}`))
  const sitemap = await (await get('/sitemap.xml')).text()
  assert.ok(sitemap.includes(`/ebooks/${book.slug}`))
  assert.ok(!sitemap.includes(seed.draft.slug))
  const renamed = `${book.slug}-revisto`
  await seed.payload.update({ collection: 'ebooks', id: book.id, data: { slug: renamed, _status: 'published' }, ...seed.auth })
  const old = await get(`/ebooks/${book.slug}`)
  assert.equal(old.status, 308)
  assert.ok(old.headers.get('location')?.endsWith(`/ebooks/${renamed}`))
  await seed.payload.update({ collection: 'offers', id: seed.offers[1].id, data: { active: true }, ...seed.auth })
  const historical = await get(`/ebooks/${book.slug}?c=${seed.campaign.code}&url=https://evil.invalid`)
  assert.equal(historical.status, 308)
  const historicalURL = new URL(historical.headers.get('location')!, base)
  assert.equal(historicalURL.searchParams.get('c'), seed.campaign.code)
  assert.equal(historicalURL.searchParams.has('url'), false)
  const historicalPage = await (await fetch(base + `/ebooks/${book.slug}?c=${seed.campaign.code}`)).text()
  assert.ok(historicalPage.includes(`comprar/${seed.offers[1].id}`), 'Slug histórico mantém a oferta afiliada.')
  assert.ok(!historicalPage.includes(`comprar/${seed.offers[0].id}`), 'Renomear livro não pode voltar ao checkout do produtor.')
  const duplicateContext = await get(`/ebooks/${book.slug}?c=${seed.campaign.code}&c=${seed.campaign.code}`)
  assert.equal(new URL(duplicateContext.headers.get('location')!, base).searchParams.getAll('c').length, 2)
  const duplicatePage = await (await fetch(base + `/ebooks/${book.slug}?c=${seed.campaign.code}&c=${seed.campaign.code}`)).text()
  assert.ok(!duplicatePage.includes(`comprar/${seed.offers[0].id}`))
  assert.ok(!duplicatePage.includes(`comprar/${seed.offers[1].id}`), 'Contexto duplicado permanece indisponível após o redirect.')
  await seed.payload.update({ collection: 'ebooks', id: book.id, data: { slug: `${renamed}-final`, _status: 'published' }, ...seed.auth })
  assert.ok((await get(`/ebooks/${book.slug}`)).headers.get('location')?.endsWith(`${renamed}-final`), 'Sem cadeia de redirecionamento.')
  await assert.rejects(seed.payload.update({ collection: 'ebooks', id: book.id, data: { slug: book.slug, _status: 'published' }, ...seed.auth }))
  console.log('B03/B04: rotas públicas, busca, drafts privados, preview autenticado, checkout/afiliado, sitemap e slugs aprovados localmente.')
} finally {
  await seed.payload.delete({ collection: 'redirects', where: { fromPath: { contains: seed.books[0].slug } }, overrideAccess: true })
  await seed.cleanup()
}
process.exit(0)
